def validate_migration_catalog():
    """Garante que cada versão declarada possui uma migration executável.

    ``SCHEMA_VERSION`` é deliberadamente separado do dicionário para evitar
    dependência circular. Sem esta guarda, incrementar apenas a constante faz
    o migrador falhar tarde com ``KeyError`` — depois de já abrir a transação.
    """

    missing = sorted(set(range(2, SCHEMA_VERSION + 1)).difference(MIGRATIONS))
    if missing:
        formatted = ", ".join(str(version) for version in missing)
        raise DatabaseMigrationError(
            f"SCHEMA_VERSION={SCHEMA_VERSION} declara migration(s) ausente(s): {formatted}."
        )


def _positive_timeout_ms(name, default):
    raw = str(os.getenv(name, default)).strip()
    try:
        value = int(raw)
    except ValueError as exc:
        raise DatabaseMigrationError(f"{name} deve ser um número inteiro em milissegundos.") from exc
    if value <= 0:
        raise DatabaseMigrationError(f"{name} deve ser maior que zero.")
    return value


def apply_migrations(connection):
    """Apply migrations with bounded waits for locks and long-running SQL."""

    validate_migration_catalog()
    lock_timeout_ms = _positive_timeout_ms("GESTOR_MIGRATION_LOCK_TIMEOUT_MS", 5000)
    statement_timeout_ms = _positive_timeout_ms(
        "GESTOR_MIGRATION_STATEMENT_TIMEOUT_MS",
        60000,
    )

    try:
        with connection.cursor() as cursor:
            # Evita que uma segunda instância fique invisível/pendurada esperando
            # indefinidamente uma migration executada por outra sessão.
            cursor.execute(
                "SELECT set_config('lock_timeout', %s, true)",
                (f"{lock_timeout_ms}ms",),
            )
            cursor.execute(
                "SELECT set_config('statement_timeout', %s, true)",
                (f"{statement_timeout_ms}ms",),
            )
            cursor.execute("SELECT pg_advisory_xact_lock(%s)", (MIGRATION_LOCK_ID,))
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS schema_migrations (
                    version INTEGER PRIMARY KEY,
                    descricao TEXT NOT NULL,
                    applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            cursor.execute("SELECT version FROM schema_migrations")
            applied_versions = {int(row["version"]) for row in cursor.fetchall()}
            current = max(applied_versions, default=0)
            if current > SCHEMA_VERSION:
                raise DatabaseMigrationError(
                    f"Schema PostgreSQL {current} é mais novo que a aplicação ({SCHEMA_VERSION})."
                )
            if 1 not in applied_versions:
                for statement in BASELINE_STATEMENTS:
                    cursor.execute(statement)
                cursor.execute(
                    "INSERT INTO schema_migrations (version, descricao) VALUES (%s, %s)",
                    (1, BASELINE_DESCRIPTION),
                )
                applied_versions.add(1)
            for version in range(2, SCHEMA_VERSION + 1):
                if version in applied_versions:
                    continue
                description, statements = MIGRATIONS[version]
                for statement in statements:
                    cursor.execute(statement)
                cursor.execute(
                    "INSERT INTO schema_migrations (version, descricao) VALUES (%s, %s)",
                    (version, description),
                )
        return SCHEMA_VERSION
    except LockNotAvailable as exc:
        logging.warning(
            "Timeout aguardando lock de migration PostgreSQL (%sms)",
            lock_timeout_ms,
        )
        raise DatabaseMigrationError(
            "Outra sessão está atualizando o schema PostgreSQL ou mantém um lock incompatível. "
            f"O Gestor aguardou {lock_timeout_ms / 1000:g}s e cancelou a inicialização."
        ) from exc
    except QueryCanceled as exc:
        logging.warning(
            "Timeout executando migration PostgreSQL (%sms)",
            statement_timeout_ms,
        )
        raise DatabaseMigrationError(
            "Uma migration PostgreSQL excedeu o tempo máximo configurado "
            f"({statement_timeout_ms / 1000:g}s)."
        ) from exc
    except DatabaseMigrationError:
        raise
    except Exception as exc:
        logging.exception("Falha ao aplicar migrations PostgreSQL")
        raise DatabaseMigrationError("Não foi possível preparar o schema PostgreSQL.") from exc
